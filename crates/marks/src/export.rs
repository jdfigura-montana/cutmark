//! Derived outputs: MKV chapters, the Markdown marks log and the CSV marks log.
//!
//! Every output is deterministic: the same sidecar always produces the same bytes.

use std::path::Path;

use crate::model::{Mark, MarkType, Sidecar, Source};
use crate::time::{format_tc, media_offset_ms, session_ms};

/// One chapter of a single media file, in that file's own time.
#[derive(Debug, Clone, PartialEq)]
pub struct Chapter {
    /// Chapter start in milliseconds from the start of the media file.
    pub start_ms: u64,
    /// Chapter end: the next chapter's start, or the end of the media file.
    pub end_ms: u64,
    /// Chapter title: the mark's label, or `Chapter N` when it has none.
    pub title: String,
}

/// Builds the chapters for one media file from its `chapter` marks.
///
/// Chapters are sorted by `t_ms`. No implicit start chapter is invented.
pub fn chapters(s: &Sidecar, media: usize) -> Vec<Chapter> {
    let mut marks: Vec<&Mark> = s.marks.iter().filter(|m| m.mark_type == MarkType::Chapter && m.media == media).collect();
    marks.sort_by_key(|m| m.t_ms);
    let duration_ms = s.media.get(media).map_or(0, |entry| entry.duration_ms);
    let ends: Vec<u64> = marks.iter().skip(1).map(|m| m.t_ms).chain(std::iter::once(duration_ms)).collect();
    marks
        .iter()
        .zip(ends)
        .enumerate()
        .map(|(position, (m, end_ms))| Chapter {
            start_ms: m.t_ms,
            end_ms,
            title: match m.label.as_deref() {
                Some(label) if !label.is_empty() => label.to_owned(),
                _ => format!("Chapter {}", position + 1),
            },
        })
        .collect()
}

/// Choices for the Markdown marks log; the default keeps the plain log.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct ExportOptions {
    /// List System marks (pause, resume and the like) in the marks table.
    pub include_system: bool,
}

/// The Markdown marks log, for people. LF line endings, no byte order mark.
pub fn markdown(s: &Sidecar) -> String {
    markdown_with(s, &ExportOptions::default())
}

/// The Markdown marks log with the given options.
pub fn markdown_with(s: &Sidecar, options: &ExportOptions) -> String {
    let base = base_name(s);
    let title = s.context.as_ref().and_then(|context| context.title.as_deref()).unwrap_or(&base);
    let total_ms = s.media.iter().fold(0u64, |sum, entry| sum.saturating_add(entry.duration_ms));

    let mut lines: Vec<String> = vec![
        format!("<!-- Generated by CutMark from {base}.marks.json. Edits are overwritten. Copy this file before annotating. -->"),
        format!("# {title}"),
        String::new(),
        format!("- Date: {}", s.session.started_at.format("%Y-%m-%d")),
        format!("- Duration: {}", format_tc(total_ms)),
    ];

    let listed = chapter_list(s);
    if !listed.is_empty() {
        lines.push(String::new());
        lines.push("## Chapters".to_owned());
        lines.push(String::new());
        lines.extend(listed.iter().map(|(start_ms, name)| format!("- {} {name}", format_tc(*start_ms))));
    }

    let has_script = any_script(s);
    let mut header = vec!["#", "Time", "Type", "Label", "Notes"];
    if has_script {
        header.push("Script");
    }
    lines.push(String::new());
    lines.push("## Marks".to_owned());
    lines.push(String::new());
    lines.push(table_row(header.iter().map(|cell| (*cell).to_owned())));
    lines.push(table_row(header.iter().map(|_| "---".to_owned())));

    let shown = s.marks.iter().filter(|m| options.include_system || m.mark_type != MarkType::System);
    for (position, m) in shown.enumerate() {
        let start = format_tc(session_ms(s, m));
        let time = match end_session_ms(s, m) {
            Some(end) => format!("{start} to {}", format_tc(end)),
            None => start,
        };
        let mut cells =
            vec![(position + 1).to_string(), time, display_type(m).to_owned(), m.label.clone().unwrap_or_default(), m.notes.clone().unwrap_or_default()];
        if has_script {
            cells.push(script_line(m).to_owned());
        }
        lines.push(table_row(cells.iter().map(|cell| escape_cell(cell))));
    }

    let mut out = lines.join("\n");
    out.push('\n');
    out
}

/// The CSV marks log, for spreadsheets: UTF-8 with a byte order mark and CRLF line endings.
pub fn csv(s: &Sidecar) -> Vec<u8> {
    let has_script = any_script(s);
    let mut header = "index,session_ms,media,t_ms,end_ms,timecode,end_timecode,type,label,notes,source".to_owned();
    if has_script {
        header.push_str(",script");
    }

    let mut out = String::from('\u{feff}');
    out.push_str(&header);
    out.push_str("\r\n");

    for (index, m) in s.marks.iter().enumerate() {
        let start = session_ms(s, m);
        let mut fields = vec![
            index.to_string(),
            start.to_string(),
            m.media.to_string(),
            m.t_ms.to_string(),
            m.end_ms.map(|end| end.to_string()).unwrap_or_default(),
            format_tc(start),
            end_session_ms(s, m).map(format_tc).unwrap_or_default(),
            wire_type(m).to_owned(),
            m.label.clone().unwrap_or_default(),
            m.notes.clone().unwrap_or_default(),
            wire_source(m.source).to_owned(),
        ];
        if has_script {
            fields.push(script_line(m).to_owned());
        }
        let row: Vec<String> = fields.iter().map(|field| csv_field(field)).collect();
        out.push_str(&row.join(","));
        out.push_str("\r\n");
    }
    out.into_bytes()
}

/// The first media file's name without its final extension, or an empty string with no media.
fn base_name(s: &Sidecar) -> String {
    s.media.first().and_then(|entry| Path::new(&entry.path).file_stem()).map(|stem| stem.to_string_lossy().into_owned()).unwrap_or_default()
}

/// Chapter start (session time) and title for every media file, in session order.
fn chapter_list(s: &Sidecar) -> Vec<(u64, String)> {
    let mut listed: Vec<(u64, String)> = Vec::new();
    for index in 0..s.media.len() {
        let offset_ms = media_offset_ms(s, index);
        listed.extend(chapters(s, index).into_iter().map(|chapter| (offset_ms.saturating_add(chapter.start_ms), chapter.title)));
    }
    listed.sort_by_key(|(start_ms, _)| *start_ms);
    listed
}

/// True when any mark carries a script line.
fn any_script(s: &Sidecar) -> bool {
    s.marks.iter().any(|m| m.script.is_some())
}

/// The text of a mark's script line, or an empty string.
fn script_line(m: &Mark) -> &str {
    m.script.as_ref().map_or("", |script| script.line.as_str())
}

/// Session time of a mark's end, if it is a range.
fn end_session_ms(s: &Sidecar, m: &Mark) -> Option<u64> {
    m.end_ms.map(|end| media_offset_ms(s, m.media).saturating_add(end))
}

/// The type name shown to people: the original unknown name if the reader kept one.
fn display_type(m: &Mark) -> &str {
    if let Some(original) = m.original_type.as_deref() {
        return original;
    }
    match m.mark_type {
        MarkType::Highlight => "Highlight",
        MarkType::Cut => "Cut",
        MarkType::Retake => "Retake",
        MarkType::Chapter => "Chapter",
        MarkType::Note => "Note",
        MarkType::BRoll => "B-roll",
        MarkType::System => "System",
    }
}

/// The type name on the wire (snake_case): the original unknown name if the reader kept one.
fn wire_type(m: &Mark) -> &str {
    if let Some(original) = m.original_type.as_deref() {
        return original;
    }
    match m.mark_type {
        MarkType::Highlight => "highlight",
        MarkType::Cut => "cut",
        MarkType::Retake => "retake",
        MarkType::Chapter => "chapter",
        MarkType::Note => "note",
        MarkType::BRoll => "b_roll",
        MarkType::System => "system",
    }
}

/// The source name on the wire (snake_case).
fn wire_source(source: Source) -> &'static str {
    match source {
        Source::Hotkey => "hotkey",
        Source::Ui => "ui",
        Source::Api => "api",
        Source::Guest => "guest",
        Source::Auto => "auto",
    }
}

/// One Markdown table row: `| a | b |`.
fn table_row(cells: impl Iterator<Item = String>) -> String {
    let cells: Vec<String> = cells.collect();
    format!("| {} |", cells.join(" | "))
}

/// Makes text safe for one Markdown table cell: `|` becomes `\|` and line breaks become `<br>`.
fn escape_cell(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '|' => out.push_str("\\|"),
            '\r' => {
                if chars.peek() == Some(&'\n') {
                    chars.next();
                }
                out.push_str("<br>");
            }
            '\n' => out.push_str("<br>"),
            other => out.push(other),
        }
    }
    out
}

/// RFC 4180 quoting: quote only when the field has a comma, double quote, CR or LF.
fn csv_field(text: &str) -> String {
    if text.contains([',', '"', '\r', '\n']) { format!("\"{}\"", text.replace('"', "\"\"")) } else { text.to_owned() }
}
